-- =====================================================================
-- V1__create_schema.sql
-- Sample "shop" schema for the SQL MCP project (PostgreSQL 14+)
--
-- Associations:
--   employees  1 ── N employees     (self-reference: manager_id)
--   customers  1 ── N orders
--   employees  1 ── N orders        (sales_rep_id, optional)
--   categories 1 ── N products
--   orders     N ── M products      (via order_items)
--   orders     1 ── N payments
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS shop;

-- ---------------------------------------------------------------------
-- employees (self-referencing hierarchy)
-- ---------------------------------------------------------------------
CREATE TABLE shop.employees (
    employee_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name    VARCHAR(50)   NOT NULL,
    last_name     VARCHAR(50)   NOT NULL,
    email         VARCHAR(120)  NOT NULL UNIQUE,
    job_title     VARCHAR(80)   NOT NULL,
    manager_id    INTEGER       REFERENCES shop.employees (employee_id) ON DELETE RESTRICT,
    hire_date     DATE          NOT NULL,
    salary        NUMERIC(10,2) NOT NULL CHECK (salary > 0)
);
COMMENT ON TABLE  shop.employees            IS 'Staff; manager_id points to another employee (NULL = top of hierarchy)';
COMMENT ON COLUMN shop.employees.manager_id IS 'Self-reference to employees.employee_id';

-- ---------------------------------------------------------------------
-- customers
-- ---------------------------------------------------------------------
CREATE TABLE shop.customers (
    customer_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name    VARCHAR(50)  NOT NULL,
    last_name     VARCHAR(50)  NOT NULL,
    email         VARCHAR(120) NOT NULL UNIQUE,
    phone         VARCHAR(20),
    city          VARCHAR(60)  NOT NULL,
    state         VARCHAR(40),
    country       VARCHAR(60)  NOT NULL DEFAULT 'USA',
    loyalty_tier  VARCHAR(10)  NOT NULL DEFAULT 'BRONZE'
                  CHECK (loyalty_tier IN ('BRONZE','SILVER','GOLD','PLATINUM')),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);
COMMENT ON TABLE shop.customers IS 'People who place orders';

-- ---------------------------------------------------------------------
-- categories
-- ---------------------------------------------------------------------
CREATE TABLE shop.categories (
    category_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(60)  NOT NULL UNIQUE,
    description   VARCHAR(255)
);
COMMENT ON TABLE shop.categories IS 'Product categories';

-- ---------------------------------------------------------------------
-- products
-- ---------------------------------------------------------------------
CREATE TABLE shop.products (
    product_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku           VARCHAR(20)   NOT NULL UNIQUE,
    name          VARCHAR(120)  NOT NULL,
    category_id   INTEGER       NOT NULL REFERENCES shop.categories (category_id) ON DELETE RESTRICT,
    unit_price    NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
    stock_qty     INTEGER       NOT NULL DEFAULT 0 CHECK (stock_qty >= 0),
    is_active     BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now()
);
COMMENT ON TABLE shop.products IS 'Items for sale; each belongs to one category';

-- ---------------------------------------------------------------------
-- orders
-- ---------------------------------------------------------------------
CREATE TABLE shop.orders (
    order_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   INTEGER     NOT NULL REFERENCES shop.customers (customer_id) ON DELETE RESTRICT,
    sales_rep_id  INTEGER     REFERENCES shop.employees (employee_id) ON DELETE RESTRICT,
    order_date    DATE        NOT NULL DEFAULT CURRENT_DATE,
    status        VARCHAR(12) NOT NULL DEFAULT 'NEW'
                  CHECK (status IN ('NEW','PAID','SHIPPED','DELIVERED','CANCELLED')),
    ship_city     VARCHAR(60),
    notes         VARCHAR(255)
);
COMMENT ON TABLE  shop.orders              IS 'Order header; order total = SUM(order_items.quantity * order_items.unit_price)';
COMMENT ON COLUMN shop.orders.sales_rep_id IS 'Employee credited with the sale (optional)';

-- ---------------------------------------------------------------------
-- order_items (junction: orders N ── M products)
-- ---------------------------------------------------------------------
CREATE TABLE shop.order_items (
    order_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      INTEGER       NOT NULL REFERENCES shop.orders (order_id)     ON DELETE RESTRICT,
    product_id    INTEGER       NOT NULL REFERENCES shop.products (product_id) ON DELETE RESTRICT,
    quantity      INTEGER       NOT NULL CHECK (quantity > 0),
    unit_price    NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
    discount_pct  NUMERIC(5,2)  NOT NULL DEFAULT 0 CHECK (discount_pct BETWEEN 0 AND 100),
    CONSTRAINT uq_order_product UNIQUE (order_id, product_id)
);
COMMENT ON TABLE  shop.order_items            IS 'Line items; resolves the many-to-many between orders and products';
COMMENT ON COLUMN shop.order_items.unit_price IS 'Price at time of order (may differ from products.unit_price)';

-- ---------------------------------------------------------------------
-- payments
-- ---------------------------------------------------------------------
CREATE TABLE shop.payments (
    payment_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      INTEGER       NOT NULL REFERENCES shop.orders (order_id) ON DELETE RESTRICT,
    amount        NUMERIC(10,2) NOT NULL CHECK (amount > 0),
    method        VARCHAR(12)   NOT NULL CHECK (method IN ('CARD','PAYPAL','BANK','GIFT_CARD')),
    paid_at       TIMESTAMPTZ   NOT NULL DEFAULT now()
);
COMMENT ON TABLE shop.payments IS 'Payments against an order (an order can have several)';

-- ---------------------------------------------------------------------
-- Indexes on foreign keys and common filters
-- ---------------------------------------------------------------------
CREATE INDEX ix_employees_manager    ON shop.employees   (manager_id);
CREATE INDEX ix_products_category    ON shop.products    (category_id);
CREATE INDEX ix_orders_customer      ON shop.orders      (customer_id);
CREATE INDEX ix_orders_sales_rep     ON shop.orders      (sales_rep_id);
CREATE INDEX ix_orders_date_status   ON shop.orders      (order_date, status);
CREATE INDEX ix_order_items_product  ON shop.order_items (product_id);
CREATE INDEX ix_payments_order       ON shop.payments    (order_id);
