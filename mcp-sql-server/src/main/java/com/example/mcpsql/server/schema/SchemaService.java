package com.example.mcpsql.server.schema;

import com.example.mcpsql.server.dto.ColumnInfo;
import com.example.mcpsql.server.dto.ForeignKeyInfo;
import com.example.mcpsql.server.dto.IndexInfo;
import com.example.mcpsql.server.dto.TableDetail;
import com.example.mcpsql.server.dto.TableInfo;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;
import java.util.stream.Collectors;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Service;

/**
 * Reads table metadata from the system catalogs. Structure is cached because it only changes through
 * Flyway, which runs at startup; row estimates are not.
 */
@Service
public class SchemaService {

    private static final String SCHEMA = "shop";
    private static final String COLUMN_SEPARATOR = ",";

    private static final String BUSINESS_RULES = """
            Business rules:
            - Order total = SUM(quantity * unit_price * (1 - discount_pct / 100)) over shop.order_items. There is no stored total column.
            - Revenue excludes orders with status CANCELLED.
            - Use order_items.unit_price for historical sales and products.unit_price for the current list price.
            """;

    private static final String TABLES_SQL = """
            SELECT c.relname, c.reltuples::bigint AS row_estimate, obj_description(c.oid, 'pg_class') AS comment
            FROM pg_class c
            JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname = ? AND c.relkind IN ('r', 'p', 'v', 'm')
            ORDER BY c.relname
            """;

    private static final String COLUMNS_SQL = """
            SELECT a.attname,
                   format_type(a.atttypid, a.atttypmod) AS type,
                   NOT a.attnotnull AS nullable,
                   CASE a.attidentity
                       WHEN 'a' THEN 'generated always as identity'
                       WHEN 'd' THEN 'generated by default as identity'
                       ELSE pg_get_expr(d.adbin, d.adrelid)
                   END AS default_value,
                   EXISTS (SELECT 1 FROM pg_index i
                           WHERE i.indrelid = c.oid AND i.indisprimary AND a.attnum = ANY (i.indkey)) AS primary_key,
                   col_description(c.oid, a.attnum) AS comment
            FROM pg_attribute a
            JOIN pg_class c ON c.oid = a.attrelid
            JOIN pg_namespace n ON n.oid = c.relnamespace
            LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
            WHERE n.nspname = ? AND c.relname = ? AND a.attnum > 0 AND NOT a.attisdropped
            ORDER BY a.attnum
            """;

    private static final String FOREIGN_KEYS_SQL = """
            SELECT con.conname,
                   (SELECT string_agg(a.attname, ',' ORDER BY k.ord)
                    FROM unnest(con.conkey) WITH ORDINALITY AS k(attnum, ord)
                    JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.attnum) AS columns,
                   rn.nspname || '.' || rc.relname AS referenced_table,
                   (SELECT string_agg(a.attname, ',' ORDER BY k.ord)
                    FROM unnest(con.confkey) WITH ORDINALITY AS k(attnum, ord)
                    JOIN pg_attribute a ON a.attrelid = con.confrelid AND a.attnum = k.attnum) AS referenced_columns
            FROM pg_constraint con
            JOIN pg_class c ON c.oid = con.conrelid
            JOIN pg_namespace n ON n.oid = c.relnamespace
            JOIN pg_class rc ON rc.oid = con.confrelid
            JOIN pg_namespace rn ON rn.oid = rc.relnamespace
            WHERE con.contype = 'f' AND n.nspname = ? AND c.relname = ?
            ORDER BY con.conname
            """;

    private static final String INDEXES_SQL = """
            SELECT indexname, indexdef FROM pg_indexes WHERE schemaname = ? AND tablename = ? ORDER BY indexname
            """;

    private final JdbcTemplate jdbc;
    private final Map<String, TableDetail> details = new ConcurrentHashMap<>();
    private volatile String overview;

    public SchemaService(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    public List<TableInfo> listTables() {
        return jdbc.query(TABLES_SQL, (rs, n) -> {
            long estimate = rs.getLong("row_estimate");
            return new TableInfo(SCHEMA, rs.getString("relname"), estimate < 0 ? null : estimate, rs.getString("comment"));
        }, SCHEMA);
    }

    /** @param table {@code orders} or {@code shop.orders} */
    public TableDetail describeTable(String table) {
        String name = tableName(table);
        TableInfo info = listTables().stream()
                .filter(candidate -> candidate.table().equals(name))
                .findFirst()
                .orElseThrow(() -> new IllegalArgumentException("Unknown table: " + table));
        return details.computeIfAbsent(name, key -> loadDetail(info));
    }

    /** Every table, column and foreign key as compact text, followed by the business rules. */
    public String overview() {
        String text = overview;
        if (text == null) {
            text = listTables().stream()
                    .map(table -> describeTable(table.table()))
                    .map(SchemaService::summarize)
                    .collect(Collectors.joining("\n", "", "\n\n" + BUSINESS_RULES));
            overview = text;
        }
        return text;
    }

    private static String tableName(String table) {
        String name = table == null ? "" : table.strip().replace("\"", "").toLowerCase(Locale.ROOT);
        return name.startsWith(SCHEMA + ".") ? name.substring(SCHEMA.length() + 1) : name;
    }

    private TableDetail loadDetail(TableInfo info) {
        String name = info.table();
        List<ColumnInfo> columns = jdbc.query(COLUMNS_SQL, (rs, n) -> new ColumnInfo(
                rs.getString("attname"),
                rs.getString("type"),
                rs.getBoolean("nullable"),
                rs.getString("default_value"),
                rs.getBoolean("primary_key"),
                rs.getString("comment")), SCHEMA, name);
        List<ForeignKeyInfo> foreignKeys = jdbc.query(FOREIGN_KEYS_SQL, (rs, n) -> new ForeignKeyInfo(
                rs.getString("conname"),
                List.of(rs.getString("columns").split(COLUMN_SEPARATOR)),
                rs.getString("referenced_table"),
                List.of(rs.getString("referenced_columns").split(COLUMN_SEPARATOR))), SCHEMA, name);
        List<IndexInfo> indexes = jdbc.query(INDEXES_SQL,
                (rs, n) -> new IndexInfo(rs.getString("indexname"), rs.getString("indexdef")), SCHEMA, name);
        return new TableDetail(SCHEMA, name, info.comment(), columns, foreignKeys, indexes);
    }

    private static String summarize(TableDetail table) {
        String columns = table.columns().stream()
                .map(column -> summarize(column, table.foreignKeys()))
                .collect(Collectors.joining(", "));
        return table.schema() + "." + table.table() + "(" + columns + ")";
    }

    private static String summarize(ColumnInfo column, List<ForeignKeyInfo> foreignKeys) {
        StringBuilder text = new StringBuilder(column.name()).append(' ').append(column.type());
        if (column.primaryKey()) {
            text.append(" PK");
        } else if (!column.nullable()) {
            text.append(" NOT NULL");
        }
        for (ForeignKeyInfo key : foreignKeys) {
            int position = key.columns().indexOf(column.name());
            if (position >= 0) {
                text.append(" FK->").append(key.referencedTable()).append('.').append(key.referencedColumns().get(position));
            }
        }
        return text.toString();
    }
}
